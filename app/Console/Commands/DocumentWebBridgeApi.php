<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;
use Illuminate\Foundation\Http\FormRequest;
use Illuminate\Routing\Route;
use Illuminate\Support\Facades\Route as RouteFacade;
use Illuminate\Support\Str;
use ReflectionMethod;
use ReflectionNamedType;
use Throwable;

/**
 * Writes app/Swagger/WebBridgeControllerDocs.php: Swagger docblocks for every mobile API route that
 * reuses a web action (names api.v1.web.*). Request bodies come from the web FormRequest's rules,
 * so the docs follow the code. Run after adding such a route, then php artisan l5-swagger:generate.
 */
class DocumentWebBridgeApi extends Command
{
    protected $signature = 'api:document-web-bridge';

    protected $description = 'Generate Swagger docs for the API routes that reuse web actions (api.v1.web.*).';

    public function handle(): int
    {
        $blocks = [];
        foreach (RouteFacade::getRoutes() as $route) {
            if (! str_starts_with((string) $route->getName(), 'api.v1.web.')) {
                continue;
            }
            foreach (array_diff($route->methods(), ['HEAD']) as $method) {
                $blocks[] = $this->block($route, $method);
            }
        }

        $body = implode("\n *\n", $blocks);
        $php = <<<PHP
<?php

namespace App\\Swagger;

/**
 * GENERATED by `php artisan api:document-web-bridge` — do not edit by hand.
 * Mobile API routes that run the web controller action itself (same FormRequest, policy, service,
 * notifications and flash message as the web; see App\\Support\\ApiBridge). Writes answer
 * {status, message: <the web's flash message>, data: {url, route, params}}; pages answer the page data.
 *
{$body}
 */
class WebBridgeControllerDocs
{
}

PHP;
        file_put_contents(app_path('Swagger/WebBridgeControllerDocs.php'), $php);
        $this->info(count($blocks).' operations written to app/Swagger/WebBridgeControllerDocs.php');

        return self::SUCCESS;
    }

    private function block(Route $route, string $method): string
    {
        $name = Str::after((string) $route->getName(), 'api.v1.web.');
        $uri = '/'.$route->uri();
        $segments = explode('/', $route->uri());
        $tag = Str::headline(($segments[2] ?? '') === '' || str_starts_with($segments[2] ?? '', '{') ? $segments[1] : $segments[1].' '.$segments[2]);
        $auth = in_array('auth:sanctum', $route->gatherMiddleware(), true);
        $action = (string) $route->getActionName();
        $lines = [
            ' * @OA\\'.Str::ucfirst(Str::lower($method)).'(',
            ' *     path="'.preg_replace('/\{(\w+)(?::\w+)?\??\}/', '{$1}', $uri).'",',
            ' *     summary="'.Str::headline(str_replace(['.', 'portal '], [' ', 'client '], $name)).'",',
            ' *     description="Runs the web action '.class_basename(Str::before($action, '@')).'@'.Str::after($action, '@').' (web route '.$name.') — identical validation, permissions and notifications.",',
            ' *     operationId="web'.Str::studly(str_replace('.', ' ', $name)).Str::ucfirst(Str::lower($method)).'",',
            ' *     tags={"'.$tag.'"},',
        ];
        if ($auth) {
            $lines[] = ' *     security={{"sanctum": {}}},';
        }
        preg_match_all('/\{(\w+)(?::\w+)?(\?)?\}/', $route->uri(), $params, PREG_SET_ORDER);
        foreach ($params as $param) {
            $lines[] = ' *     @OA\\Parameter(name="'.$param[1].'", in="path", required='.(isset($param[2]) && $param[2] === '?' ? 'false' : 'true').', @OA\\Schema(type="string")),';
        }
        if (in_array($method, ['POST', 'PUT', 'PATCH'], true) && ($rules = $this->rules($action)) !== []) {
            $props = [];
            $required = [];
            foreach ($rules as $field => $rule) {
                if (str_contains($field, '*') || str_contains($field, '.')) {
                    continue;
                }
                $text = is_array($rule) ? implode('|', array_filter($rule, 'is_string')) : (string) $rule;
                $type = str_contains($text, 'array') ? 'array' : (str_contains($text, 'integer') ? 'integer' : (str_contains($text, 'numeric') ? 'number' : (str_contains($text, 'boolean') ? 'boolean' : (str_contains($text, 'file') ? 'string' : 'string'))));
                $props[] = ' *             @OA\\Property(property="'.$field.'", type="'.$type.'"'.($type === 'array' ? ', @OA\\Items(type="object")' : '').(str_contains($text, 'file') ? ', format="binary"' : '').', description="'.str_replace('"', "'", Str::limit($text, 120)).'")';
                if (str_starts_with($text, 'required') || str_contains($text, '|required')) {
                    $required[] = '"'.$field.'"';
                }
            }
            $media = collect($rules)->contains(fn ($r) => str_contains(is_array($r) ? implode('|', array_filter($r, 'is_string')) : (string) $r, 'file')) ? 'multipart/form-data' : 'application/json';
            $lines[] = ' *     @OA\\RequestBody(required=true, @OA\\MediaType(mediaType="'.$media.'", @OA\\Schema(type="object", required={'.implode(', ', $required).'},';
            $lines[] = implode(",\n", $props);
            $lines[] = ' *     ))),';
        }
        $lines[] = ' *     @OA\\Response(response=200, description="Success (page data, or the web\'s flash message + next route); files stream as application/pdf etc.", @OA\\JsonContent(type="object", @OA\\Property(property="status", type="string", example="Success"), @OA\\Property(property="message", type="string"), @OA\\Property(property="data", type="object"))),';
        if ($auth) {
            $lines[] = ' *     @OA\\Response(response=401, description="Unauthenticated"),';
            $lines[] = ' *     @OA\\Response(response=403, description="Forbidden (account type, organization permission or plan)"),';
        }
        $lines[] = ' *     @OA\\Response(response=404, description="Not found / belongs to another organization"),';
        $lines[] = ' *     @OA\\Response(response=422, description="Validation error or the web\'s error message", @OA\\JsonContent(type="object", @OA\\Property(property="status", type="string", example="Failed"), @OA\\Property(property="message", type="string"), @OA\\Property(property="errors", type="object")))';
        $lines[] = ' * )';

        return implode("\n", $lines);
    }

    /** @return array<string, mixed> Rules of the action's FormRequest (empty when the action validates inline). */
    private function rules(string $action): array
    {
        if (! str_contains($action, '@')) {
            return [];
        }
        try {
            foreach ((new ReflectionMethod(Str::before($action, '@'), Str::after($action, '@')))->getParameters() as $parameter) {
                $type = $parameter->getType();
                if ($type instanceof ReflectionNamedType && is_subclass_of($type->getName(), FormRequest::class)) {
                    $request = $type->getName()::create('/', 'POST');
                    $request->setContainer(app())->setRedirector(app('redirect'));

                    return method_exists($request, 'rules') ? (array) app()->call([$request, 'rules']) : [];
                }
            }
        } catch (Throwable) {
            return [];
        }

        return [];
    }
}
